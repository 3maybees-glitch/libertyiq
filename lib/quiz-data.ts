export function getQuizByTopicId(topicId: string): Quiz | undefined {
  const quiz = allQuizzes.find((q) => q.topicId === topicId);
  if (!quiz) return undefined;

  // Normalize levels to ensure they have all required properties
  const normalizedLevels = quiz.levels.map((level) => ({
    ...level,
    rankTitle: level.rankTitle || level.rankEarned,
    rankId: level.rankId || (level.difficulty === 'easy' ? 'intern' : level.difficulty === 'medium' ? 'fellow' : 'chief'),
  }));

  return {
    levels: normalizedLevels,
    topicTitle: quiz.topicTitle || quiz.topicName,
  };
}

export function getAllTopicIds(): string[] {
  return allQuizzes.map((q) => q.topicId);
}
